#: What a name/symbol may contain. Deliberately narrow: a token whose name
#: carries control characters, zero-width joiners or a right-to-left override is
#: a token built to be misread on somebody's screen, and this rail will not mint
#: one. ASCII printable, no leading/trailing space.
MAX_NAME_CHARS = 64
MAX_SYMBOL_CHARS = 16
MAX_DECIMALS = 18
#: 1e15 whole units at 18 decimals is already a thousand trillion. Above this a
#: "supply" is a typo, and a typo that mints is not recoverable.
MAX_WHOLE_SUPPLY = 10 ** 15


class TokenTemplateError(ValueError):
    """The requested token cannot be built. Always carries the reason."""


def _validate_text(value: str, *, field: str, limit: int) -> str:
    if not isinstance(value, str):
        raise TokenTemplateError(f"{field} must be text")
    text = value.strip()
    if not text:
        raise TokenTemplateError(f"{field} cannot be empty")
    if len(text) > limit:
        raise TokenTemplateError(
            f"{field} is {len(text)} characters, above the {limit}-character limit")
    for ch in text:
        if ord(ch) < 0x20 or ord(ch) == 0x7F:
            raise TokenTemplateError(
                f"{field} contains a control character — a token name that can "
                f"hide part of itself on a screen is not one this rail will mint")
        if 0x200B <= ord(ch) <= 0x200F or 0x202A <= ord(ch) <= 0x202E or ord(ch) == 0xFEFF:
            raise TokenTemplateError(
                f"{field} contains a zero-width or bidirectional-override "
                f"character (U+{ord(ch):04X}) — those exist to make a name read "
                f"as a different name")
    return text


def _abi_encode_string(text: str) -> str:
    raw = text.encode("utf-8")
    padded = raw.hex().ljust(((len(raw) + 31) // 32) * 64, "0") if raw else ""
    return f"{len(raw):064x}" + padded


def encode_constructor_args(*, name: str, symbol: str, decimals: int,
                            supply_raw: int) -> str:
    """ABI-encode ``(string,string,uint8,uint256)`` — hex WITHOUT ``0x``.

    Hand-rolled rather than pulled from web3: this tree has no ABI encoder, the
    shape is fixed and small, and the round-trip is pinned by a unit test that
    decodes the output back.
    """
    name = _validate_text(name, field="name", limit=MAX_NAME_CHARS)
    symbol = _validate_text(symbol, field="symbol", limit=MAX_SYMBOL_CHARS)
    if not isinstance(decimals, int) or isinstance(decimals, bool):
        raise TokenTemplateError("decimals must be a whole number")
    if not 0 <= decimals <= MAX_DECIMALS:
        raise TokenTemplateError(
            f"decimals must be between 0 and {MAX_DECIMALS}, got {decimals}")
    if not isinstance(supply_raw, int) or isinstance(supply_raw, bool):
        raise TokenTemplateError("supply must be a whole number")
    if supply_raw <= 0:
        raise TokenTemplateError(
            "supply must be greater than zero — the constructor reverts on zero, "
            "so this would burn the fee for nothing")
    if supply_raw >= 2 ** 256:
        raise TokenTemplateError("supply does not fit in uint256")

    head_words = 4
    name_offset = head_words * 32
    name_encoded = _abi_encode_string(name)
    symbol_offset = name_offset + len(name_encoded) // 2
    return ("".join((
        f"{name_offset:064x}",
        f"{symbol_offset:064x}",
        f"{decimals:064x}",
        f"{supply_raw:064x}",
    )) + name_encoded + _abi_encode_string(symbol))


def build_init_code(*, name: str, symbol: str, decimals: int,
                    supply_raw: int) -> str:
    """The full 0x-prefixed create payload: pinned init code + encoded args."""
    return INIT_CODE + encode_constructor_args(
        name=name, symbol=symbol, decimals=decimals, supply_raw=supply_raw)


def whole_to_raw(supply: float, decimals: int) -> int:
    """Whole units -> raw units, EXACTLY.

    ⚠️ Decimal, not float, and this is not fastidiousness. The first live dry
    run on prod (2026-09-13) asked for a supply of 1,000,000,000 and the guard
    reported ``1000000000000000013287555072`` — because ``1e9 * 10**18`` in
    binary floating point is not ``1e27``, and above 2^53 the error is in the
    integer part. The token would have been minted with a supply nobody asked
    for, on a contract with no mint function, forever.

    ``1.5`` at 0 decimals still refuses: it is not 1 and not 2, it is a caller
    who has not said what they mean, and silently truncating a SUPPLY is not a
    rounding error anyone can undo later.
    """
    from decimal import Decimal, InvalidOperation

    if supply <= 0:
        raise TokenTemplateError("supply must be greater than zero")
    if supply > MAX_WHOLE_SUPPLY:
        raise TokenTemplateError(
            f"a supply of {supply:g} whole units is above the "
            f"{MAX_WHOLE_SUPPLY:g} sanity ceiling — refusing a number this large "
            f"as a typo, because minting is not reversible")
    try:
        # str() first: Decimal(float) would faithfully carry the binary error in.
        scaled = Decimal(str(supply)) * (Decimal(10) ** int(decimals))
    except (InvalidOperation, ValueError, ArithmeticError) as exc:
        raise TokenTemplateError(f"supply {supply!r} is not a usable number ({exc})")
    if scaled != scaled.to_integral_value():
        raise TokenTemplateError(
            f"a supply of {supply:g} is not a whole number of units at "
            f"{decimals} decimals")
    return int(scaled)
