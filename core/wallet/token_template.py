"""The ONE token the agent can mint, pinned as bytes (042).

``deploy_token`` compiles nothing at runtime and accepts no bytecode. It deploys
this artifact and only this artifact, so the safety properties below are
structural rather than promised:

* **fixed supply** — minted in full to the deployer in the constructor;
* **no mint function, no owner, no admin, no pause, no blacklist**;
* **no transfer fee, no rebase, no upgrade path, no proxy**.

The source lives beside this file (``contracts/FixedSupplyToken.sol``) so it can
be read, and ``scripts/build_token_template.py`` recompiles it and fails if the
bytes below have drifted. ``tests/unit/core/wallet/test_token_template.py`` pins
the same hashes without needing a compiler.

⚠️ The bytes are the contract. The Solidity beside them is EVIDENCE, not the
artifact — a reader who wants the guarantee should check the hash, recompile, or
read the runtime. What makes the claim enforceable at run time is
``deploy_guard``: the simulated runtime must equal :data:`RUNTIME` byte for byte
except at :data:`IMMUTABLE_SLOTS`, which is asserted BEFORE anything is signed.

Verified live 2026-09-13 on Robinhood Chain (4663) and Base (8453): deploying
this init code returns 1686 runtime bytes differing from :data:`RUNTIME` at
exactly bytes 242-250 (totalSupply) and 325 (decimals) — the two immutable
slots, and nothing else.
"""
