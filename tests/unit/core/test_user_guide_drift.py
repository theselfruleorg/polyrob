"""Drift test for the hand-written user-guide text (095 W5, rule R18).

The generated references (``references/configuration.md``,
``references/config/*``, ``references/verbs.md``) are pinned to their sources
by ``scripts/gen_user_guide_refs.py --check``. The HAND-WRITTEN files are not
generated, so this test pins what they may name:

* every backticked ``/verb`` is a live owner verb (``core/verbs.py``, a
  first-party pack verb, or a REPL approval token);
* every backticked ``polyrob …`` command resolves through the click table;
* every UPPER_SNAKE setting is a catalog row (``core/flags_catalog.py``), a
  posture member, or a named code constant;
* a posture member is named within 3 lines of ``POLYROB_OVERRIDES`` or
  ``config set`` — a member is never set by a plain env line.

``BASELINE`` holds known misses so the test could land green; it is empty and
must stay empty: fix the text, do not add a row.
"""
import re
from pathlib import Path

import click
import pytest

ROOT = Path(__file__).resolve().parents[3]
SKILLS = ROOT / "data" / "prompts" / "skills"
GENERATED = "<!-- GENERATED by scripts/gen_user_guide_refs.py"
_BLOCK = re.compile(r"<!-- BEGIN GENERATED.*?<!-- END GENERATED[^>]*-->", re.S)

#: (file name, kind, token) misses accepted while the text is fixed. Keep empty.
BASELINE: frozenset = frozenset()

#: UPPER_SNAKE names that are code constants, not settings: name -> module.
CONSTANTS = {"OWNER_DOC_MAX_CHARS": "core.instance"}

#: Backticked HTTP path roots that look like a verb (``/v1`` = the OpenAI surface).
API_ROOTS = {"/v1"}

_VERB = re.compile(r"`(/[a-z][a-z0-9_]*)(?=[\s`])")
_CMD_WORD = r"[a-z][a-z0-9_-]*"
_CMD = re.compile(rf"`(?:sudo )?polyrob ((?:{_CMD_WORD})(?: {_CMD_WORD})*)")
_FENCE_CMD = re.compile(rf"^\s*polyrob ((?:{_CMD_WORD})(?: {_CMD_WORD})*)")
_FLAG = re.compile(r"(?<![A-Za-z0-9_<>*.-])((?:[A-Z][A-Z0-9]*|<[A-Z]+>)(?:_(?:[A-Z0-9]+|<[A-Z]+>))+)"
                   r"(?![A-Za-z0-9_<>(-])")
_RULE = re.compile(r"POLYROB_OVERRIDES|config set")


def hand_written_files():
    guide = SKILLS / "polyrob-user-guide"
    files = [p for p in sorted(guide.rglob("*.md"))
             if not p.read_text().startswith(GENERATED)]
    # 095 W6: the FAQ guide page is hand-written (references/faq.md is its copy)
    return files + [SKILLS / "self-deploy" / "SKILL.md", ROOT / "docs" / "guide" / "faq.md"]


def _text(path: Path) -> str:
    # a generated block (SKILL.md docs-map, the FAQ troubleshooting) is pinned
    # by the generator; blank it, keeping line numbers
    return _BLOCK.sub(lambda m: "\n" * m.group(0).count("\n"), path.read_text())


def _pack_verbs() -> set:
    names = set()
    for py in ROOT.glob("packs/*/*/**/*.py"):
        names.update(re.findall(r'Verb\(\s*"(/[a-z_]+)"', py.read_text()))
    return names


@pytest.fixture(scope="module")
def live_verbs():
    from core import verbs
    from cli.ui.approval_prompt import _TOKENS
    names = {v.name for v in verbs.VERB_TABLE}
    names |= {a for v in verbs.VERB_TABLE for a in v.aliases}
    return names | _pack_verbs() | {"/" + t for t in _TOKENS} | API_ROOTS


@pytest.fixture(scope="module")
def resolve_command():
    import tomllib
    from cli.polyrob import cli
    packs = set()
    for manifest in ROOT.glob("packs/*/*/pack.toml"):
        packs.update((tomllib.loads(manifest.read_text()).get("cli") or {})
                     .get("commands") or ())

    def resolve(words):
        group = cli
        for i, word in enumerate(words):
            sub = group.get_command(click.Context(group), word)
            if sub is None:
                return None if (i == 0 and word in packs) else word
            if not isinstance(sub, click.Group):
                return None
            group = sub
        return None
    return resolve


@pytest.fixture(scope="module")
def known_names():
    from core.config_policy.members import MEMBER_FLAGS
    from core.flags_catalog import CATALOG, DERIVED_FROM
    exact, patterns = set(), []
    for row in CATALOG:
        if "<" in row[0]:
            patterns.append(re.compile(re.sub(r"<[^>]+>", "[A-Z0-9_]+",
                                              re.escape(row[0]).replace(r"\<", "<")
                                              .replace(r"\>", ">"))))
        exact.add(row[0])
    return exact | set(DERIVED_FROM) | set(MEMBER_FLAGS), patterns, set(MEMBER_FLAGS)


def _misses(kind, found):
    return sorted(m for m in found if m not in BASELINE)


def test_the_scan_sees_the_hand_written_files():
    names = {p.name for p in hand_written_files()}
    assert {"SKILL.md", "autonomy.md", "money-and-safety.md", "surfaces.md"} <= names
    assert not any(p.read_text().startswith(GENERATED) for p in hand_written_files())


def test_every_named_verb_is_live(live_verbs):
    found = set()
    for path in hand_written_files():
        for verb in _VERB.findall(_text(path)):
            if verb not in live_verbs:
                found.add((path.name, "verb", verb))
    misses = _misses("verb", found)
    assert not misses, f"hand-written guide names verbs that do not exist: {misses}"


def test_every_named_polyrob_command_resolves(resolve_command):
    found = set()
    for path in hand_written_files():
        text = _text(path)
        hits = _CMD.findall(text)
        in_fence = False
        for line in text.splitlines():
            if line.strip().startswith("```"):
                in_fence = not in_fence
                continue
            if in_fence:
                hits += _FENCE_CMD.findall(line)
        for hit in hits:
            bad = resolve_command(hit.split())
            if bad:
                found.add((path.name, "command", f"polyrob {hit}"))
    misses = _misses("command", found)
    assert not misses, f"hand-written guide names CLI commands that do not exist: {misses}"


def test_every_named_setting_resolves(known_names):
    import importlib
    exact, patterns, _members = known_names
    found = set()
    for path in hand_written_files():
        for name in set(_FLAG.findall(_text(path))):
            if name in exact or any(p.fullmatch(name) for p in patterns):
                continue
            if name in CONSTANTS and hasattr(importlib.import_module(CONSTANTS[name]), name):
                continue
            found.add((path.name, "setting", name))
    misses = _misses("setting", found)
    assert not misses, f"hand-written guide names unknown settings: {misses}"


def test_a_member_is_named_next_to_its_one_rule(known_names):
    _exact, _patterns, members = known_names
    found = set()
    for path in hand_written_files():
        lines = _text(path).splitlines()
        for i, line in enumerate(lines):
            for name in set(_FLAG.findall(line)) & members:
                near = "\n".join(lines[max(0, i - 3): i + 4])
                if not _RULE.search(near):
                    found.add((path.name, "member", name))
    misses = _misses("member", found)
    assert not misses, ("a posture member is named without its rule (`POLYROB_OVERRIDES` "
                        f"or `config set` within 3 lines): {misses}")


def test_baseline_is_empty():
    assert not BASELINE, "fix the text instead of growing the baseline"
