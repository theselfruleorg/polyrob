"""Contract test for the polyrob-user-guide config reference (owner-UX P3 T1).

Mirrors tests/unit/core/test_flags.py's pattern: every flag documented in the runtime catalog (core/flags_catalog.py::CATALOG) must
be discoverable in the compact reference the skill reads.
"""
import re
from pathlib import Path

from core.flags_catalog import CATALOG

REPO_ROOT = Path(__file__).resolve().parents[3]
REFERENCE = (
    REPO_ROOT / "data" / "prompts" / "skills" / "polyrob-user-guide"
    / "references" / "configuration.md"
)
CONFIG_DIR = REFERENCE.parent / "config"


def _config_text() -> str:
    """The index + every split area file (095 W5)."""
    return "\n".join(p.read_text() for p in [REFERENCE, *sorted(CONFIG_DIR.glob("*.md"))])


def test_reference_file_exists_and_has_content():
    assert REFERENCE.exists(), f"missing generated reference: {REFERENCE}"
    text = REFERENCE.read_text()
    assert text.startswith("<!-- GENERATED by scripts/gen_user_guide_refs.py")
    assert "LLM / providers" in text
    assert "references/config/llm-providers.md" in text


def test_every_catalog_flag_appears_in_reference():
    """Every flag name known to the runtime catalog must be findable in the
    compact reference (subset assertion, mirroring test_flags.py's doc-rows
    ⊆ registry pattern) — a name absent here means the skill's reference lost
    a flag the runtime still resolves.

    Dynamic-pattern names (containing ``<...>``, e.g. ``AUX_MODEL_<SLOT>``)
    are skipped: they're not resolved by literal-name lookup, so their absence
    (or presence with the placeholder unexpanded) would be a false negative —
    same tolerance test_flags.py's ``_NAME_RE`` applies by construction.
    """
    text = _config_text()
    missing = []
    for name, _group, _default, *_ in CATALOG:
        if "<" in name:
            continue
        if name not in text:
            missing.append(name)
    assert not missing, (
        f"{len(missing)} flag(s) in core/flags_catalog.py::CATALOG missing from "
        f"the user-guide reference — run `python scripts/gen_user_guide_refs.py`: "
        f"{missing[:10]}"
    )


def test_skill_text_names_the_current_owner_doc_cap():
    """The skill teaches the agent the owner-doc cap; a raised cap (16000 ->
    24000 on 2026-10-11) must not leave the old number in the skill text."""

    from core.instance import OWNER_DOC_MAX_CHARS

    skill_dir = REPO_ROOT / "data" / "prompts" / "skills" / "polyrob-user-guide"
    for path in (skill_dir / "SKILL.md", skill_dir / "references" / "setup-interview.md"):
        text = path.read_text()
        named = re.findall(r"`OWNER_DOC_MAX_CHARS` \((\d+) characters", text)
        assert named, f"{path.name} no longer names the owner-doc cap"
        assert all(int(n) == OWNER_DOC_MAX_CHARS for n in named), (path.name, named)


