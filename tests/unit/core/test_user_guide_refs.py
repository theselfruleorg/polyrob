FAQ_DOC = REPO_ROOT / "docs" / "guide" / "faq.md"
FAQ_REF = REFERENCE.parent / "faq.md"


def _generated_headings(text: str) -> list:
    start = text.index("<!-- BEGIN GENERATED troubleshooting -->")
    end = text.index("<!-- END GENERATED troubleshooting -->")
    return re.findall(r"^#### (.+)$", text[start:end], flags=re.M)


def test_faq_troubleshooting_headings_match_refusal_texts():
    """A pasted refusal or stop text finds its heading: the generated block
    holds exactly one heading per REFUSAL_KINDS owner text and per typed stop
    reason, in both the guide page and the skill reference."""
    from core.tool_gates import REFUSAL_KINDS
    from agents.task.runtime.stop_reason import StopReason, describe_stop_reason

    want = [describe_stop_reason(r) for r in StopReason]
    want += [row.owner_text or row.text for row in REFUSAL_KINDS.values()]
    for path in (FAQ_DOC, FAQ_REF):
        assert _generated_headings(path.read_text()) == want, (
            f"{path.name} troubleshooting is stale — run "
            "`python scripts/gen_user_guide_refs.py`")


def test_every_stop_reason_has_an_owner_explanation():
    from agents.task.runtime.stop_reason import OWNER_EXPLAIN, StopReason

    assert set(OWNER_EXPLAIN) == set(StopReason)
    assert all(sentence.strip() and step.strip()
               for sentence, step in OWNER_EXPLAIN.values())


def test_faq_reference_is_generated_from_the_guide_page_and_fits_one_result():
    from agents.task.agent.core.result_budget import DEFAULT_TOOL_RESULT_MAX_TOKENS

