def test_caps_block_carries_the_code_defaults(monkeypatch):
    """UG-7: the run limits the reference states are the code defaults."""
    import re as _re
    from core.config_policy import goal_flags
    from core.config_policy.capability_toggles import (
        autonomous_run_budget_usd, run_budget_usd)

    for name in ("AUTONOMOUS_MAX_STEPS", "AUTONOMOUS_RUN_BUDGET_USD", "RUN_BUDGET_USD"):
        monkeypatch.delenv(name, raising=False)
    code = {
        # a module constant read at import: take the coded default
        "INTERACTIVE_MAX_STEPS": int(_re.search(
            r'_int_env\("INTERACTIVE_MAX_STEPS", (\d+)\)',
            Path(goal_flags.__file__).read_text()).group(1)),
        "AUTONOMOUS_MAX_STEPS": goal_flags.GoalFlagsMixin.autonomous_max_steps(),
        "AUTONOMOUS_RUN_BUDGET_USD": autonomous_run_budget_usd(),
        "RUN_BUDGET_USD": run_budget_usd(),
    }
    text = REFERENCE.read_text()
    for name, value in code.items():
        m = _re.search(rf"`{name}` — default: ([0-9.]+)", text)
        assert m, f"caps block lacks {name}"
        assert float(m.group(1)) == float(value), (name, m.group(1), value)


