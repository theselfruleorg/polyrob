# ── 0009: the read returns what the SURFACE refuses to answer ──────────────
# The surface drops a mail as auto-generated by its HEADERS (OS5); the read used
# to select by SENDER NAME only, so an activation mail from `accounts@…` with
# `Auto-Submitted: auto-generated` was dropped by one and invisible to the other.

@pytest.mark.asyncio
async def test_header_flagged_mail_from_a_plain_sender_is_returned(monkeypatch):
    t = _tool()
    inbox = [
        dict(_mail("Service Accounts <accounts@service.example>", "Verify your email",
                   "Your code is 445566"), headers={"Auto-Submitted": "auto-generated"}),
        dict(_mail("Bulk Sender <hello@list.example>", "Weekly", "digest body"),
             headers={"Precedence": "bulk"}),
        dict(_mail("Owner Person <owner@example.com>", "private", "this is a human message"),
             headers={}),
    ]

    async def fake_read(folder="INBOX", limit=10, unread_only=False, since_date=None):
        return list(inbox)
    monkeypatch.setattr(t, "read_emails", fake_read)
    out = (await t.email_read_machine_mail(EmailReadMachineMailAction())).extracted_content
    assert "445566" in out
    assert "digest body" in out
    assert "this is a human message" not in out


