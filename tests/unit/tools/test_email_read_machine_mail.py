"""EmailTool.email_read_machine_mail — the agent reads its OWN machine-sent mail
(activation links, verification codes) and nothing else.

Prod 2026-10-04 12:24: Rob created an Ethereum Magicians account the owner had
authorized; the activation mail reached rob@theselfrule.org, the email surface
dropped it as auto-generated (correctly: it must never be ANSWERED), and the
agent had no way to read it, so the goal blocked on the owner clicking a link.

Human mail stays on the gated surface path: this action returns only mail from a
no-reply style sender, and it reads with the existing non-consuming
`read_emails` (BODY.PEEK), so it never steals the surface's UNSEEN queue."""
import pytest

from tools.email_tool import EmailReadMachineMailAction, EmailTool
from tests.unit.tools.test_email_send_action import _tool


def _mail(frm, subject, content):
    return {"id": "1", "from": frm, "subject": subject, "date": "Sun, 4 Oct 2026 12:24:39 +0000",
            "content": content, "html_content": ""}


@pytest.fixture
def tool(monkeypatch):
    t = _tool()
    inbox = [
        _mail("Fellowship of Ethereum Magicians <noreply@discourse.example>",
              "[Ethereum Magicians] Confirm your new account",
              "Click here to activate: https://ethereum-magicians.example/u/activate-account/abc123\n"),
        _mail("Owner Person <owner@example.com>", "private", "this is a human message"),
        _mail("GitHub <no-reply@github.example>", "Your code", "Code: 991122"),
    ]

    async def fake_read(folder="INBOX", limit=10, unread_only=False, since_date=None):
        fake_read.calls.append(dict(folder=folder, limit=limit, unread_only=unread_only))
        return list(inbox)
    fake_read.calls = []
    monkeypatch.setattr(t, "read_emails", fake_read)
    t._fake_read = fake_read
    return t


@pytest.mark.asyncio
async def test_returns_machine_mail_with_its_links(tool):
    res = await tool.email_read_machine_mail(EmailReadMachineMailAction())
