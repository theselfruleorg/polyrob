"""Seat-skill and rail-pin helpers for agent construction.

Extracted from ``construction.py`` (proposal 095 P0.2) as verbatim code-motion;
``construction.py`` re-exports every name for back-compat (tests import them
from there). Every import is lazy, inside the function, as before.
"""


def rail_skill_ids(agent) -> list:
	"""060 WS-5: the skill ids this session's RAIL pins, in order, deduplicated —
	the orchestrator stamp (cron/goal ``payload.skills`` via the session request)
	plus ``TaskSessionConfig.skills``. Only string ids; [] when none."""
	ids = list(getattr(getattr(agent, "orchestrator", None), "_rail_skill_ids", None) or [])
	cfg = getattr(agent, "session_config", None)
	ids += list(getattr(cfg, "skills", None) or [])
	return [str(i).strip() for i in dict.fromkeys(ids) if isinstance(i, str) and i.strip()]


#: 093 C2: the skills every OWNER chat seat pins. ⚠️ Never rename a pinned id
#: (``harness-manual`` is generated by ``devtools/gen_harness_manual.py``).
OWNER_SEAT_SKILLS = ("harness-manual",)


def owner_seat_skill_ids(agent) -> list:
	"""093 C2: :data:`OWNER_SEAT_SKILLS` when this session is an owner chat seat
	(``core.autonomy_marker.is_owner_seat`` — stamped before construction) or,
	095 W2, a goal/cron run (``is_autonomous``: a refusal there has nobody to ask
	live, so the manual is what says who can act), else []. A delegated sub-agent
	(a leaf) shares its parent's session id but is not the seat: it gets [] (the
	index line only). A room or correspondent session gets [] too. Fail-closed."""
	if getattr(agent, "_is_sub_agent", False) or getattr(agent, "_role", None) == "leaf":
		return []
	try:
		from core.autonomy_marker import is_autonomous, is_owner_seat
		sid = getattr(getattr(agent, "orchestrator", None), "session_id", None)
		return list(OWNER_SEAT_SKILLS) if (is_owner_seat(sid) or is_autonomous(sid)) else []
	except Exception:
		return []


def report_missing_rail_skills(agent, pinned: list, matched) -> list:
	"""A skill the rail NAMED that did not load says so (060 WS-7 fail-loud):
	a WARNING in the journal and a ``rail_skill_missing`` event the ``rules``
	status section renders. The run continues with the skill index."""
	loaded = {getattr(s, "skill_id", None) for s in (matched or [])}
	missing = [sid for sid in pinned if sid not in loaded]
	if not missing:
		return []
	orch = getattr(agent, "orchestrator", None)
	agent.logger.warning(
		"rail pinned skill(s) %s but they did not load (unknown id or no SKILL.md) — "
		"running with the skill index only", missing)
	from core.event_kinds import RAIL_SKILL_MISSING
	from core.event_log import emit
	emit(RAIL_SKILL_MISSING, source="construction",
	     user_id=str(getattr(orch, "user_id", "") or ""),
	     session_id=str(getattr(orch, "session_id", "") or ""),
	     attrs={"missing": missing, "pinned": list(pinned)})
	return missing
